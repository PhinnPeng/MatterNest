/**
 * 剥掉 TS/TSX 的注释与字符串内容，供 `check.mjs` 的源码断言（禁令⑨ / ⑫）做正则匹配。
 *
 * ## 为什么必须剥（禁令⑨ 的第一版没剥，当场被自己绊倒）
 *
 * 第一版只靠「窄形态」防误伤，理由写的是「注释里会写 `now.slice(0, 10)`，
 * 不含 `toISOString()` 就天然排除了」。**那个假设是错的** ——
 * 禁令自己的文档注释里就完整写了那个表达式（解释为什么不能用它），
 * 于是门禁上线第一次运行就报了 `risks.ts` 的**注释**。
 *
 * 教训与禁令⑧ 同源：**注释里出现的值不算命中**。解释「不要用 X」这件事
 * 自然要把 X 写出来 —— 这是文档的正常形态，不是违规。所以剥注释是必需的，不是保险。
 *
 * 字符串**内容**一并剥掉是同一个理由的另一半：`"<List"` / `"direction="` 这种
 * 被引号包着的字面量，不该被当成「有人真的在用它」（禁令⑫）。
 *
 * ## 契约：**行号要对得上原文**
 *
 * 剥掉的字符不再输出，但**每一个换行都原样保留**（块注释内、字符串内也一样）。
 * 于是 `剥后文本.split("\n")` 的段数与原文相同，源码断言报出的 `:行号` 可以直接跳。
 *
 * 2026-10-16 补上这一条（禁令⑫ 要按行定位）：不保留换行时，
 * `matter-detail.tsx` 那种跨行块注释（382–396）会把**它后面所有行号整体推前十几行**
 * —— 报错指错地方比不报还坏。禁令⑨ 只用 `test()`、不报行号，所以它一直没暴露这个问题。
 *
 * ## 怎么工作
 *
 * 单趟扫描，维护「当前是否在字符串里」与「是否在块注释里」两个状态。
 * 字符串含 `'` `"` `` ` `` 三种；模板串里的 `${…}` 不单独解析（近似足够）。
 *
 * **字符串内的 `//` 不会开启行注释**：字符串分支在 `/` 判断之前 ——
 * 这条是有意的，`href="https://…"` 在本仓到处都是。
 *
 * ## 已知边界（不假装完备）
 *
 * · 正则字面量里若含引号（如 `/["']/`）会让配对错位 —— 方向是**多剥**
 *   （把后面的代码当注释），也就是可能**漏报**而不是误报。本仓当前没有这种字面量；
 *   真出现时用它的那条断言会静默变松，它自己的 canary 抓不到这种情形。
 *
 * @param {string} code 原始 TS/TSX
 * @returns {string} 只剥内容、不剥换行的近似源码
 */
export function stripTsComments(code) {
  let out = "";
  let i = 0;
  let quote = null;
  let inBlock = false;
  /** 内容可以丢，换行必须留 —— 见文件头「行号要对得上原文」 */
  const keepNewline = (ch) => {
    if (ch === "\n") out += ch;
  };

  while (i < code.length) {
    const ch = code[i];
    const next = code[i + 1];

    if (inBlock) {
      if (ch === "*" && next === "/") {
        inBlock = false;
        i += 2;
      } else {
        keepNewline(ch);
        i++;
      }
      continue;
    }
    if (quote) {
      if (ch === "\\") {
        // 转义的下一个字符也属于字符串内容，一起剥；若它是换行（行连续符）则保留换行
        keepNewline(next);
        i += 2;
        continue;
      }
      if (ch === quote) quote = null;
      else keepNewline(ch);
      i++;
      continue;
    }
    if (ch === "'" || ch === '"' || ch === "`") {
      quote = ch;
      i++;
      continue;
    }
    if (ch === "/" && next === "/") {
      // 行注释：吃到行尾（换行保留，免得把两行拼成一行）
      while (i < code.length && code[i] !== "\n") i++;
      continue;
    }
    if (ch === "/" && next === "*") {
      inBlock = true;
      i += 2;
      continue;
    }
    out += ch;
    i++;
  }
  return out;
}
