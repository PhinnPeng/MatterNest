--
-- 权威出处：MATT-74 的裁定评论（2026-10-13，方案 A）+ `docs/research-croner-status-heartbeat.md`
-- （croner 状态面的一手实测研究）。本文件只是那两条结论的落地，不含新判断。
--
-- ## 为什么要一张**新表**，而不是复用现有配置表
--
-- 应用内定时器（`src/instrumentation.ts`，MATT-74）每 5 分钟调一次通知泵；
-- 「它还在跑吗」这个问题**在进程内无解**：croner@10.0.1 的全部状态是进程内存字段
-- （`src/croner.ts:63-86` 九个键），进程一死全部归零，而**进程内的观察者无法报告
-- 自己进程的死亡**。研究文档 §8 逐条排除了 croner 的四个候选信号：
--
--   · `isRunning()` 不读 timer 句柄（`:357-366`，四个条件里没有一个是它）⇒ 实测把句柄
--     置空后它仍返回 `true`；它答的是「我是否**被允许**触发」，不是「我是否**还会**触发」。
--   · `previousRun()` 在 `finally` 里赋值（`:547-554`）⇒ **抛异常照样前进**：它记「跑完了」
--     不是「跑成了」，成功与失败产出**字节相同**的状态。所以它不能当心跳时间戳。
--   · `previousRuns(n)` 是**纯模式推算**，一个从未运行过的任务照样返回三个时间戳。
--   · `lastRun()` 在 10.0.1 上**不存在**（`typeof job.lastRun === "undefined"`），别照旧稿写。
--
-- 能突破这条逻辑必然的只有**进程外的见证者** —— 这张表就是那个见证者。
-- 复用现有配置表被用户否决（那要先论证哪张表语义合适，等于把一件确定的事拖成待查的事）。
--
-- ## 三种状态靠「行存在 + 可空时间戳」表达（已裁，不可重开）
--
-- | 状态 | 怎么看 |
-- |---|---|
-- | 从未跑过 | 行存在但 `created_at IS NULL`（seed 落的初始行就是这个态） |
-- | 跑过且新鲜 | `now() - created_at < 15 分钟` |
-- | 跑过但停摆 | `now() - created_at >= 15 分钟`（3 个周期） |
--
-- ⚠ 只有「有行 / 没行」两种态的表，探针只能报「有行/没行」，那就退回
-- 「静默零事件与没人该收同形」那个坑 —— 那个坑正是这张表存在的理由。
-- 所以 `created_at` **故意可空、故意没有 DEFAULT**：NULL 携带语义（从未跑过），
-- 不是「还没填」。有 DEFAULT `now()` 就等于「插入即算跑过」，那个态会被从表里删掉。
-- 列名沿用票面裁定里的检测口径（原文逐字写的是 `created_at IS NULL`）。
--
-- ## 单行由**约束**钉住（已裁，不可重开）
--
-- `CHECK (id = 1)` + 主键 ⇒ **这张表物理上不可能出现第二行**。
-- 不能靠「代码只写一行」的自觉：两行 = 两个心跳 = 探针读到较新那行，
-- 掩盖掉真正在停摆的那条。两个机制各自都拦不住，合起来才拦得住。
--
-- ## 消费口径（写给 MATT-74，三条都不是建议）
--
-- 1. **只在 pump 成功后写**：`created_at = now()`，一次 UPDATE，不 INSERT（行是 seed 落的）。
--    失败**不动**这行 —— 这正是 `previousRun()` 做不到的那件事（它在失败时也前进）。
-- 2. **`pump_count = pump_count + 1` 单语句原子自增**，不「先查再加」。
--    它记的是**成功次数**，所以它同时也是「本行确实被泵写过」的见证：seed 的初始行是 0。
--    ⚠ 它**不是** `mn_notification_event.merge_count`（那是「同窗口内通知合并了几次」，
--    另一张表另一个语义）。MATT-74 描述里那句「`merge_count = merge_count + 1` 是单语句原子操作」
--    说的是事件表的合并计数，别把那个列名搬到这张表上来。
-- 3. **不写 croner 的 `previousRun()` / `nextRun()`**：那是定时器的状态，不是泵的结果。
--    把「定时器到点了」写进来，会让「到点但泵抛异常」看起来像一次成功心跳。
--
-- ## 丢轮（`protect: true`）这张表看得到多少 —— 照实写
--
-- 研究文档 §5.2 的结论：`protect` 命中时**跳过该轮且不触发任何回调**（静默丢弃），
-- 而 `previousRun()` 仍在前进 ⇒ 从 croner 的状态面完全看不出丢过轮。
-- **被丢的那一轮不产生任何回调，所以它也没有写者** —— 库侧同样拿不到精确的丢轮计数，
-- 这不是本表的缺陷，是「无人执行 ⇒ 无人上报」的同一件事。
-- 能拿到的是**停摆的粒度**：探针报「距上次成功已 N 个周期」（`floor(age / 5min)`），
-- 于是「泵变慢/持续超时（丢轮）」与「定时器压根没起来」在 num_cycles 上分得开
-- （前者是 1–2 个周期后仍在动，后者是从头到尾不涨）。精确计数要另立机制，不在本票。
--
-- ## 时间列
--
-- `created_at` 是 `timestamptz`（会话已钉 UTC，修订稿 §12.2）。不软删、无审计列、
-- 无 `updated_at`：它不是业务表，是 instrumentation 物 —— 单行、原地覆写，
-- `created_at` 每次心跳都被重写，再放一个 `updated_at` 与它永远同值，是纯冗余。
--
-- DOWN（前滚优先，但人要看得懂丢了什么）：
--   DROP TABLE "mn_timer_heartbeat";
--   ⇒ 只是把见证者删掉，泵本身不受影响。⚠ 真要回退必须**同时**摘掉
--      `src/instrumentation.ts` 里那次写，否则它会因为表不存在而每 5 分钟抛一次。
CREATE TABLE "mn_timer_heartbeat" (
	"id" bigint PRIMARY KEY NOT NULL,
	"created_at" timestamp with time zone,
	"pump_count" bigint DEFAULT 0 NOT NULL,
	CONSTRAINT "ck_mn_timer_heartbeat_id" CHECK (id = 1)
);
