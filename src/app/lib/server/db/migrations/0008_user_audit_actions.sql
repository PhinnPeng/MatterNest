-- 背景：F6-1（账号启停）与 F6-9（本地凭据设置/重置）都要求落审计，而 §3.3 的动作值域里
-- 没有能表达这两件事的值。E03 已把落点定为 `target_type='app_user'`（迁移 0006 放开的
